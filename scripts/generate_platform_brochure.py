def _screenshot_flowables(
    filenames_with_captions: list[tuple[str, str]],
    styles: dict[str, ParagraphStyle],
    *,
    max_width: float = 16.5 * cm,
) -> list:
    """Build flowables for each screenshot file that exists on disk.

    Missing files are silently skipped so the brochure still builds when only
    a few screenshots have been captured. Each image is rendered at the given
    max width with aspect preserved, followed by a caption.
    """
    flowables: list = []
    for fname, caption in filenames_with_captions:
        path = SCREENSHOTS_DIR / fname
        if not path.exists():
            continue
        try:
            img = Image(str(path))
            ratio = img.imageHeight / img.imageWidth if img.imageWidth else 1
            img.drawWidth = max_width
            img.drawHeight = max_width * ratio
        except Exception:
            # Don't let a corrupt PNG kill the whole build.
            continue
        block: list = [img, Spacer(1, 0.1 * cm)]
        block.append(Paragraph(f"<i>{caption}</i>", styles["body_muted"]))
        block.append(Spacer(1, 0.5 * cm))
        # KeepTogether so a screenshot doesn't get split across pages.
        flowables.append(KeepTogether(block))
    return flowables


def role_pages(styles: dict[str, ParagraphStyle]) -> list:
    story: list = []
    story.append(Paragraph("Roles & capabilities", styles["section_title"]))
    story.append(
        Paragraph(
            "Five distinct roles, each with a tightly scoped surface. The Tutor "
            "platform never blurs the line between curation, administration, "
            "instruction, and learning.",
            styles["section_subtitle"],
        )
    )
    story.append(Spacer(1, 0.2 * cm))

    for role in ROLES:
        # Coloured chip header.
        chip = Table(
            [[Paragraph(role["name"].upper(), styles["role_chip"])]],
            colWidths=[5.5 * cm],
        )
        chip.setStyle(
            TableStyle([
                ("BACKGROUND", (0, 0), (-1, -1), colors.HexColor(role["color"])),
                ("TEXTCOLOR", (0, 0), (-1, -1), colors.white),
                ("LEFTPADDING", (0, 0), (-1, -1), 8),
                ("RIGHTPADDING", (0, 0), (-1, -1), 8),
                ("TOPPADDING", (0, 0), (-1, -1), 4),
                ("BOTTOMPADDING", (0, 0), (-1, -1), 4),
            ])
        )
        # Header + bullets stay together.
        header_block: list = [chip, Spacer(1, 0.1 * cm)]
        header_block.append(Paragraph(role["subtitle"], styles["body_muted"]))
        header_block.append(Spacer(1, 0.15 * cm))
        items = [
            ListItem(Paragraph(f, styles["bullet"]), leftIndent=10, value=None)
            for f in role["features"]
        ]
        header_block.append(
            ListFlowable(
                items, bulletType="bullet", start="•",
                leftIndent=14, bulletFontName="Helvetica-Bold",
            )
        )
        header_block.append(Spacer(1, 0.4 * cm))
        story.append(KeepTogether(header_block))

        # Screenshots specific to this role, embedded one per row underneath
        # the bullets. Skipped silently if the PNG isn't present.
        screenshots = ROLE_SCREENSHOTS.get(role["key"], [])
        story.extend(_screenshot_flowables(screenshots, styles))

        story.append(PageBreak())
    return story


def highlights_page(styles: dict[str, ParagraphStyle]) -> list:
    """A 'highlight reel' section with the cross-cutting screenshots.

    Skipped entirely if no highlight screenshots have been captured yet.
    """
    flowables = _screenshot_flowables(HIGHLIGHT_SCREENSHOTS, styles)
    if not flowables:
        return []

    story: list = []
    story.append(Paragraph("Highlights", styles["section_title"]))
    story.append(
        Paragraph(
            "A few standout surfaces that don't fit neatly into one role.",
            styles["section_subtitle"],
        )
    )
    story.extend(flowables)
    story.append(PageBreak())
    return story



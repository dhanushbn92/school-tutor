def page_decoration(canvas, doc):
    """Header band + footer with page number on every non-cover page."""
    canvas.saveState()
    page_num = canvas.getPageNumber()
    if page_num == 1:
        canvas.restoreState()
        return
    width, height = A4
    # Slim coloured rule at top
    canvas.setFillColor(colors.HexColor(PRIMARY_HEX))
    canvas.rect(0, height - 0.4 * cm, width, 0.4 * cm, fill=1, stroke=0)
    # Header text
    canvas.setFillColor(colors.HexColor(MUTED_HEX))
    canvas.setFont("Helvetica", 8)
    canvas.drawString(2 * cm, height - 1.0 * cm, "School Tutor — platform overview")
    canvas.drawRightString(width - 2 * cm, height - 1.0 * cm, f"Page {page_num}")
    canvas.restoreState()


def cover_decoration(canvas, doc):
    """Cover page: full-bleed colour band + logo lockup placeholder."""
    canvas.saveState()
    width, height = A4
    canvas.setFillColor(colors.HexColor(PRIMARY_DARK_HEX))
    canvas.rect(0, height - 6 * cm, width, 6 * cm, fill=1, stroke=0)
    canvas.setFillColor(colors.white)
    canvas.setFont("Helvetica-Bold", 12)
    canvas.drawString(2 * cm, height - 1.4 * cm, "SCHOOL TUTOR")
    canvas.setFont("Helvetica", 10)
    canvas.drawString(2 * cm, height - 2.0 * cm, "Platform overview & feature catalog")
    canvas.restoreState()



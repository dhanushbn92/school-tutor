def build_feature_map(out_path: Path) -> None:
    """One landscape PNG with all five roles, content types, and analytics."""
    fig = plt.figure(figsize=(16, 9), facecolor="white")
    ax = fig.add_axes([0, 0, 1, 1])
    ax.set_xlim(0, 16)
    ax.set_ylim(0, 9)
    ax.axis("off")

    # Top banner
    banner = mpatches.FancyBboxPatch(
        (0, 8.0), 16, 1.0,
        boxstyle="square,pad=0",
        facecolor=PRIMARY_DARK_HEX, edgecolor="none",
    )
    ax.add_patch(banner)
    ax.text(0.5, 8.62, "SCHOOL TUTOR",
            color="white", fontsize=22, fontweight="bold", va="center")
    ax.text(0.5, 8.22, TAGLINE,
            color="#cbd5e1", fontsize=12, va="center")
    ax.text(15.5, 8.45, "Platform feature map",
            color="white", fontsize=11, va="center", ha="right",
            fontstyle="italic")

    # Five role cards across.
    n = len(ROLES)
    margin_x = 0.4
    gap = 0.18
    total_w = 16 - 2 * margin_x - (n - 1) * gap
    card_w = total_w / n
    card_top = 7.6
    card_bottom = 3.7
    card_h = card_top - card_bottom

    for i, role in enumerate(ROLES):
        x = margin_x + i * (card_w + gap)
        # Card background
        card = mpatches.FancyBboxPatch(
            (x, card_bottom), card_w, card_h,
            boxstyle="round,pad=0.02,rounding_size=0.18",
            facecolor=CARD_BG_HEX, edgecolor="#cbd5e1", linewidth=1,
        )
        ax.add_patch(card)
        # Coloured header strip at the top of the card
        head = mpatches.FancyBboxPatch(
            (x, card_top - 0.7), card_w, 0.7,
            boxstyle="round,pad=0.02,rounding_size=0.18",
            facecolor=role["color"], edgecolor="none",
        )
        ax.add_patch(head)
        # Cover the rounded bottom of the head with a flat strip so it
        # blends into the card body.
        ax.add_patch(
            mpatches.Rectangle(
                (x + 0.05, card_top - 0.7),
                card_w - 0.10, 0.18,
                facecolor=role["color"], edgecolor="none",
            )
        )
        ax.text(x + card_w / 2, card_top - 0.32,
                role["name"],
                color="white", fontsize=12, fontweight="bold",
                ha="center", va="center")
        ax.text(x + card_w / 2, card_top - 0.55,
                role["subtitle"],
                color="white", fontsize=8.5, alpha=0.85,
                ha="center", va="center", fontstyle="italic")

        # Bullet list. matplotlib's `ax.text` doesn't wrap by default, so we
        # split each bullet into multiple lines manually with textwrap and
        # render line-by-line at the right line spacing.
        bullets = role["short_features"][:4]
        wrap_width = 26                 # characters per line, ~card_w wide
        line_height = 0.21              # axis units per text line
        bullet_gap = 0.16               # extra space between bullets
        cursor_y = card_top - 1.0
        for b in bullets:
            wrapped = textwrap.wrap(b, width=wrap_width) or [""]
            # Bullet glyph aligned with the first line.
            ax.text(x + 0.20, cursor_y, "•",
                    fontsize=11, color=role["color"],
                    fontweight="bold", va="top")
            for i, line in enumerate(wrapped):
                ax.text(x + 0.45, cursor_y - i * line_height, line,
                        fontsize=9, color="#0f172a", va="top")
            cursor_y -= line_height * len(wrapped) + bullet_gap

    # Bottom band: content types + analytics callouts
    band_top = 3.4
    band_h = 2.7
    # Left card: content
    cl = mpatches.FancyBboxPatch(
        (0.4, band_top - band_h), 7.6, band_h,
        boxstyle="round,pad=0.02,rounding_size=0.18",
        facecolor=SOFT_BG_HEX, edgecolor="#c7d2fe", linewidth=1,
    )
    ax.add_patch(cl)
    ax.text(0.7, band_top - 0.35, "Content catalog",
            fontsize=13, fontweight="bold", color=PRIMARY_DARK_HEX, va="center")
    ax.text(0.7, band_top - 0.75,
            "AI-generated, human-curated, served to every classroom",
            fontsize=9, color=MUTED_HEX, va="center", fontstyle="italic")
    # Render content types as a wrapped block of " · " separated names so
    # nothing spills off the card.
    content_names = [c[0] for c in CONTENT_TYPES]
    catalog_text = " · ".join(content_names)
    catalog_lines = textwrap.wrap(catalog_text, width=68)
    cy = band_top - 1.20
    for line in catalog_lines[:3]:
        ax.text(0.7, cy, line,
                fontsize=9.5, color="#0f172a", va="center")
        cy -= 0.32
    ax.text(0.7, cy - 0.10,
            "PDFs render inline · simulations open as interactive 3D · diagrams scale as SVG.",
            fontsize=9, color=MUTED_HEX, va="center", fontstyle="italic")

    # Right card: analytics + AI tutor
    cr = mpatches.FancyBboxPatch(
        (8.2, band_top - band_h), 7.4, band_h,
        boxstyle="round,pad=0.02,rounding_size=0.18",
        facecolor="#ecfdf5", edgecolor="#bbf7d0", linewidth=1,
    )
    ax.add_patch(cr)
    ax.text(8.5, band_top - 0.35, "Analytics & AI tutor",
            fontsize=13, fontweight="bold",
            color="#065f46", va="center")
    ax.text(8.5, band_top - 0.75,
            "Insight that makes the catalog actionable",
            fontsize=9, color=MUTED_HEX, va="center", fontstyle="italic")
    analytics_chips = [
        ("Cognitive buckets", "Factual · Understanding · Application"),
        ("Weak topics",        "Class-wise · per-bucket breakdown"),
        ("Trends",             "Per-student over time"),
        ("AI tutor",           "Chapter / topic-scoped, refuses off-topic"),
    ]
    line_y = band_top - 1.20
    for label, body in analytics_chips:
        ax.text(8.5, line_y,
                f"• {label}: ",
                fontsize=10, color="#065f46",
                fontweight="bold", va="top")
        ax.text(11.2, line_y, body,
                fontsize=10, color="#0f172a", va="top")
        line_y -= 0.40

    # Footer
    ax.text(0.4, 0.4,
            "School Tutor · CBSE/NCERT-aligned · "
            "Multi-tenant: each school is isolated, individual learners are tenants of one.",
            fontsize=9, color=MUTED_HEX, va="center")
    ax.text(15.6, 0.4,
            f"Generated {date.today().isoformat()}",
            fontsize=8.5, color=MUTED_HEX, va="center", ha="right",
            fontstyle="italic")

    fig.savefig(out_path, dpi=150, bbox_inches="tight", facecolor="white")
    plt.close(fig)


